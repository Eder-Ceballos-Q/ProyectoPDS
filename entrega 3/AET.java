public class AET {
    String tipo;
    String nombre;
    String fechaInicio;
    String fechaFin;
    int id;
    String descripcion;

    public AET(String tipo, String nombre, String fechaInicio, String fechaFin, int id, String descripcion) {
        this.tipo = tipo;
        this.nombre = nombre;
        this.fechaInicio = fechaInicio;
        this.fechaFin = fechaFin;
        this.id = id;
        this.descripcion = descripcion;
    }
}
